def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default=".")
    ap.add_argument("--output", required=True)
    args = ap.parse_args()
    project = Path(args.project).resolve()
    spec = json.loads((project / "refine-logs/MATH_SPEC.json").read_text(encoding="utf-8"))
    design = json.loads((project / "refine-logs/design_card.json").read_text(encoding="utf-8"))
    design.pop("experiment_type", None)
    spec["source_design_sha256"] = hashlib.sha256(
        json.dumps(design, sort_keys=True, ensure_ascii=False).encode("utf-8")
    ).hexdigest()
    spec["formulas"] = list(spec["formulas"]) + FORMULAS
    spec["symbol_table"] = list(spec.get("symbol_table", [])) + SYMBOLS
    spec["deployment_extension"] = {
        "scope": "English-only behavior generation and English-rubric scoring; no BFI-2/TIPI text",
        "authoritative_scientific_spec": "refine-logs/MATH_SPEC.json",
    }
    target = (project / args.output).resolve()
    if not target.is_relative_to(project):
        raise ValueError("output escapes project")
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix(target.suffix + f".tmp-{os.getpid()}")
    temp.write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(temp, target)
    print(target)


if __name__ == "__main__":
    main()
