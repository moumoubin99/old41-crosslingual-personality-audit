#!/usr/bin/env python3
"""Build the Extraversion persona-pole generation queue for bjb1.

Two non-gating phases (high / low) x the four registered checkpoints x the 23
qualification seeds the existing NEUTRAL B0 arm actually used (20260811-20260834
minus the stuck 20260829, which is never scheduled or retried).

Every job is the same generator argv as that checkpoint's own B0 job with only
--phase, --prompt-config and --freeze-receipt changed, which is why each job
carries the B0 formula manifest/evidence of the identical code path it reuses.
With .aris/OPERATOR_SKIP_FORMULA present, pilot_budget skips verify_deployment
and never opens that directory, so the pointer is provenance for the reused code
path and not a review PASS for the pole argv; the manifest notes say so.

Regenerates process/experiment_queue/english_b4_poles_queue.json byte-for-byte.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


PROJECT = "<LOCAL_PATH>/41-2026-09-05-aris-3"
DEPLOYMENT_ROOT = "<LOCAL_PATH>/project41"
PYTHON = "<LOCAL_PATH>/python3.12"
IDEA = "xling-induced-personality-transfer-matrix"

PROMPT_CONFIG = "process/consumption/frozen/english_execution_v2.json"
FREEZE_RECEIPT = "process/consumption/frozen/english_execution_receipt_v2.json"

# Seed 20260829 has no usable source cluster anywhere in this study.
