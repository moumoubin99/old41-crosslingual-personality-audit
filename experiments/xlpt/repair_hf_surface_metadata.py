#!/usr/bin/env python3
"""Rewrite the provenance fields a stale generator stamped on the zh shards.

The worker ran the 2026-09-21 revision of ``run_hf_generation.py`` for the three
Hugging-Face checkpoints (aya-expanse-8b, Llama-3.1-8B-Instruct, gemma-3-12b-it).
That revision predates the Chinese surface: it hardcodes the English record
literals and derives ``eligible_for_analysis`` from the *English* phase name, so
a ``zh-b0-competence`` row came out stamped

    eligible_for_analysis  True   (should be False -- this is the G1 screen)
    surface_scope          "English-only; no BFI-2/TIPI item text"
    persona_language       "English"
    dialogue_language      "English"   (should be "Chinese")

even though the phase, the setting, the scenarios and the transcripts are the
Chinese ones.  qwen3-8b runs through the other entry point and is unaffected.

Those four fields are statements *about the phase*, not measurements, so they are
recoverable without GPU: ``phase_surface()`` is their definition.  This tool
copies the phase tree to a new root and replaces exactly those four values, and
only when the row carries exactly the stale English literals.  Any other
difference is refused rather than papered over, and the originals are never
touched -- the repaired tree is a sibling directory, so both are on record.

One thing is **not** recoverable here.  The stale revision also never passed
``facts_label``, so the user turns of those shards carry the English label
``Account and policy facts:`` where the frozen v3 config renders
``账户和政策事实:``.  That is prompt content, not metadata, and rewriting it would
be a lie about what the model was shown.  Every repaired row therefore carries a
``facts_label_deviation`` field naming the label that was actually used, and the
repair receipt repeats it, so the deviation travels with the data wherever these
shards are reported.

    python3 -m experiments.xlpt.repair_hf_surface_metadata --project .
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

from experiments.xlpt.run_transformers_generation import (
    ENGLISH_SURFACE,
    FACTS_LABEL_EN,
    phase_surface,
)

PHASE = "zh-b0-competence"
DEFAULT_ROOT = f"process/results/xlpt/{PHASE}"
DEFAULT_OUT = f"process/results/xlpt/{PHASE}-repaired"
DEFAULT_RECEIPT = "process/results/xlpt/ZH_B0_METADATA_REPAIR.json"

# What the 2026-09-21 generator stamped, exactly. A row that differs from this in
# any way other than already being correct is not a case this tool understands.
STALE = {
    "eligible_for_analysis": True,
    "surface_scope": ENGLISH_SURFACE["surface_scope"],
    "persona_language": ENGLISH_SURFACE["persona_language"],
    "dialogue_language": ENGLISH_SURFACE["dialogue_language"],
}

DEVIATION = (
    "generated by the 2026-09-21 run_hf_generation.py, which did not pass the frozen "
    f"facts_label: the scenario facts were introduced with {FACTS_LABEL_EN!r} instead of the "
    "v3-frozen Chinese label. Prompt content, not repaired here; the provenance fields were "
    "restored from the phase spec."
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def repair_rows(rows, shard: Path):
    """Return (rows, repaired_count). Raises on anything that is not the known stamp."""
    expected = phase_surface(rows[0]["phase"])
    repaired = 0
    for row in rows:
        if row["phase"] != rows[0]["phase"]:
            raise SystemExit(f"{shard}: rows disagree on phase")
        current = {key: row.get(key) for key in STALE}
        if current == {key: expected[key] for key in STALE}:
            continue
        if current != STALE:
            raise SystemExit(
                f"{shard}: surface fields are neither the phase's own nor the known stale "
                f"stamp ({current}); refusing to guess what generated this row"
            )
        for key in STALE:
            row[key] = expected[key]
        row["facts_label_deviation"] = DEVIATION
        repaired += 1
    return rows, repaired


def run(args) -> int:
    root = Path(args.project).resolve()
    phase_root = (root / args.phase_root).resolve()
    out_root = (root / args.out_root).resolve()
    for path in (phase_root, out_root):
        if not str(path).startswith(str(root)):
            raise SystemExit("both roots must stay inside the project")
    shards = sorted(phase_root.glob("*/seed-*.jsonl"))
    if not shards:
        raise SystemExit(f"no shards under {phase_root}")

    report = []
    for shard in shards:
        rows = [json.loads(line) for line in shard.read_text(encoding="utf-8").splitlines() if line.strip()]
        if not rows:
            raise SystemExit(f"{shard}: empty shard")
        source_sha = sha256(shard)
        rows, repaired = repair_rows(rows, shard)
        target = out_root / shard.parent.name / shard.name
        entry = {
            "shard": str(shard.relative_to(root)),
            "checkpoint": shard.parent.name,
            "rows": len(rows),
            "rows_repaired": repaired,
            "source_sha256": source_sha,
        }
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            if repaired:
                text = "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)
                target.write_text(text, encoding="utf-8")
            else:
                # Byte-for-byte copy: an untouched shard stays untouched.
                shutil.copyfile(shard, target)
            entry["output"] = str(target.relative_to(root))
            entry["output_sha256"] = sha256(target)
        report.append(entry)

    receipt = {
        "tool": "experiments/xlpt/repair_hf_surface_metadata.py",
        "phase": PHASE,
        "source_root": str(phase_root.relative_to(root)),
        "repaired_root": str(out_root.relative_to(root)),
        "fields_repaired": sorted(STALE),
        "repaired_from": "experiments/xlpt/run_transformers_generation.py:phase_surface()",
        "facts_label_deviation": DEVIATION,
        "shards": len(report),
        "shards_repaired": sum(1 for e in report if e["rows_repaired"]),
        "rows_repaired": sum(e["rows_repaired"] for e in report),
        "detail": report,
    }
    if not args.check:
        receipt_path = root / args.receipt
        receipt_path.parent.mkdir(parents=True, exist_ok=True)
        receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        receipt["receipt"] = args.receipt
    print(json.dumps({key: value for key, value in receipt.items() if key != "detail"}, ensure_ascii=False))
    return 0


def parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--project", default=".")
    ap.add_argument("--phase-root", default=DEFAULT_ROOT)
    ap.add_argument("--out-root", default=DEFAULT_OUT)
    ap.add_argument("--receipt", default=DEFAULT_RECEIPT)
    ap.add_argument("--check", action="store_true",
                    help="validate every shard against the known stamp without writing anything")
    return ap


if __name__ == "__main__":
    raise SystemExit(run(parser().parse_args()))
